/* Draws text at (x, y) panel pixels, each font pixel = scale x scale. Returns width drawn. */
int fb_text(struct fb *f, int x, int y, int scale, const char *s, uint32_t fg, uint32_t bg) {
    int x0 = x;
    for (; *s; s++) {
        int c = (unsigned char)*s;
        if (c >= 'a' && c <= 'z') c -= 32;
        if (c < 32 || c > 90) c = '?';
        const uint8_t *g = glyphs[c - 32];
        fb_fill(f, x, y, 6 * scale, 8 * scale, bg); /* cell incl. 1px spacing */
        for (int row = 0; row < 7; row++)
            for (int col = 0; col < 5; col++)
                if (g[row] & (16 >> col)) fb_fill(f, x + col * scale, y + row * scale, scale, scale, fg);
        x += 6 * scale;
    }
    return x - x0;
}
