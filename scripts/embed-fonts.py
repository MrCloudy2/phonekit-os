#!/usr/bin/env python3
"""Writes a C file embedding the Roboto weights paneld's gfx.c draws with.  embed-fonts.py <assets/fonts> <out.c>"""
import sys
src, out = sys.argv[1], sys.argv[2]
names = {"font_light": "Roboto-Light.ttf", "font_regular": "Roboto-Regular.ttf",
         "font_medium": "Roboto-Medium.ttf", "font_bold": "Roboto-Bold.ttf"}
with open(out, "w") as f:
    f.write("/* generated by scripts/embed-fonts.py from assets/fonts (Roboto, Apache 2.0) */\n")
    for sym, fn in names.items():
        data = open(f"{src}/{fn}", "rb").read()
        f.write(f"const unsigned char {sym}[{len(data)}] __attribute__((aligned(4))) = {{")
        f.write(",".join(str(b) for b in data))
        f.write("};\n")
