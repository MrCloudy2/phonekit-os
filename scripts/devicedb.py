#!/usr/bin/env python3
"""Device database (M15): validate devices/*/device.yaml and generate docs/devices.md.

  scripts/devicedb.py check        exit 1 on any error (CI)
  scripts/devicedb.py table        rewrite docs/devices.md

Needs PyYAML (`pip install pyyaml`). The schema is deliberately small: the fields a porter must fill, plus a
`milestones` map (M0..M17 -> "confirmed <date> (...)" / "partial ..." / "not started").
"""
import glob
import os
import re
import sys

try:
    import yaml
except ImportError:
    sys.exit("devicedb: needs PyYAML (pip install pyyaml)")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REQUIRED = {
    "identity": ["name", "model", "soc"],
    "boot": ["flash_tool", "partition", "partition_size"],
    "display": ["api"],
    "input": [],
    "usb": ["udc"],
}
STAGES = [("M0", "boots"), ("M2", "touch"), ("M4", "power"), ("M5", "USB modes"), ("M6", "SCREEN"),
          ("M6e", "rotation"), ("M7", "PPJ/1"), ("M12b", "PHONEBOX"), ("M10", "Wi-Fi")]


def load(path):
    with open(path) as f:
        return yaml.safe_load(f) or {}


def check_one(path, d):
    errs = []
    if d.get("schema") != 0:
        errs.append("schema: must be 0")
    for sec, keys in REQUIRED.items():
        if not isinstance(d.get(sec), dict):
            errs.append(f"{sec}: missing section")
            continue
        for k in keys:
            if d[sec].get(k) in (None, ""):
                errs.append(f"{sec}.{k}: missing")
    dev = os.path.basename(os.path.dirname(path))
    if dev != "_template" and not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)+", dev):
        errs.append(f"folder name '{dev}' should be <vendor>-<codename>, lowercase")
    mk = os.path.join(os.path.dirname(path), "device.mk")
    if not os.path.exists(mk):
        errs.append("device.mk missing next to device.yaml")
    soc_dir = (d.get("identity") or {}).get("soc_dir")
    if soc_dir and not os.path.isdir(os.path.join(ROOT, soc_dir)):
        errs.append(f"identity.soc_dir: {soc_dir} does not exist")
    ms = d.get("milestones") or {}
    if not isinstance(ms, dict):
        errs.append("milestones: must be a map like {M0: 'confirmed 2026-01-01'}")
    else:
        for k in ms:
            if not re.fullmatch(r"M\d+[a-z]?", str(k)):
                errs.append(f"milestones.{k}: not a milestone id")
    return errs


def devices():
    for path in sorted(glob.glob(os.path.join(ROOT, "devices", "*", "device.yaml"))):
        if "/_template/" in path:
            continue
        yield path, load(path)


def cmd_check():
    bad = 0
    for path, d in devices():
        errs = check_one(path, d)
        rel = os.path.relpath(path, ROOT)
        print(f"{'ok ' if not errs else 'ERR'} {rel}")
        for e in errs:
            print(f"    {e}")
        bad += bool(errs)
    return 1 if bad else 0


def mark(v):
    v = str(v or "").lower()
    return "✅" if v.startswith("confirmed") else "🟨" if v.startswith(("partial", "in progress", "started")) else "⬜"


def verified(dev):
    """'<commit>, <date>, <n> passes' from devices/<dev>/pptest-baseline.txt (written by ppregress.py --update)."""
    p = os.path.join(ROOT, "devices", dev, "pptest-baseline.txt")
    if not os.path.exists(p):
        return "not yet"
    head = open(p).readline()
    m = re.search(r"passed at (\S+), (\d{4}-\d\d-\d\d)", head)
    n = sum(int(f[2]) for f in (l.rstrip("\n").split("\t") for l in open(p)) if len(f) > 3 and f[1] == "PASS")
    return f"`{m.group(1)}` {m.group(2)}, {n} passes" if m else "?"


def cmd_table():
    rows = []
    for path, d in devices():
        idn, ms = d.get("identity") or {}, d.get("milestones") or {}
        dev = os.path.basename(os.path.dirname(path))
        soc = idn.get("soc", "")
        rows.append(f"| [{idn.get('name', dev)}](../devices/{dev}/device.yaml) | {idn.get('model', '')} | {soc} | "
                    + " | ".join(mark(ms.get(m)) for m, _ in STAGES) + f" | {verified(dev)} |")
    out = os.path.join(ROOT, "docs", "devices.md")
    with open(out, "w") as f:
        f.write("# Supported devices\n\nGenerated by `scripts/devicedb.py table` from `devices/*/device.yaml`; don't edit by hand.\n"
                "✅ confirmed on the phone · 🟨 partly · ⬜ not yet. Details in each device's record and `docs/verification/`.\n"
                "**Verified at**: the commit the phone last passed pptest at, from its `pptest-baseline.txt`\n"
                "(`scripts/ppregress.py <dev> --update` after a full run). Build that commit for an image tested on that\n"
                "phone; newer commits only passed CI there (`paneld-config.txt`, `footprint.txt`). `-dirty`: the run\n"
                "had uncommitted changes on top.\n\n")
        f.write("| Device | Model | SoC | " + " | ".join(f"{label} ({m})" for m, label in STAGES) + " | Verified at |\n")
        f.write("|---|---|---|" + "---|" * len(STAGES) + "---|\n")
        f.write("\n".join(rows) + "\n")
        f.write("\nPort yours: [porting guide](porting-guide.md) · `scripts/probe.sh` drafts a record from the phone.\n")
    print(f"wrote {os.path.relpath(out, ROOT)} ({len(rows)} devices)")
    return 0


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    sys.exit(cmd_check() if cmd == "check" else cmd_table() if cmd == "table" else f"usage: {__doc__}")
